export const getBranchById = (id: BranchId | number, branches: BranchConfig[] = INITIAL_BRANCH_LIST): BranchConfig => {
  const strId = String(id);
  const found = branches.find((b) => String(b.id) === strId || (strId === 'b1' && b.id === '1') || (strId === 'b2' && b.id === '2') || (strId === 'b3' && b.id === '5'));
  return found || branches[0] || BRANCH_MAIN;
};
