// Devanagari numeral converter
export const toDevanagariNumerals = (num?: number | string | null): string => {
  if (num === null || num === undefined) return '';
  const devanagariDigits = ['०', '१', '२', '३', '४', '५', '६', '७', '८', '९'];
  return String(num).replace(/[0-9]/g, (digit) => devanagariDigits[parseInt(digit, 10)]);
};

